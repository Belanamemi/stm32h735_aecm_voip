/**
 * Encode PCM16 to G.711 A-law
 */
void g711_alaw_encode(const int16_t *pcm16, uint8_t *output, uint32_t len) {
    for (uint32_t i = 0; i < len; i++) {
        int16_t sample = pcm16[i];
        uint8_t alaw;
        
        /* Determine sign and absolute value */
        int sign = (sample >> 8) & 0x80;
        if (sign != 0) sample = -sample;
        if (sample > 32635) sample = 32635;
        
        /* Find exponent and mantissa */
        int exponent = 7;
        uint16_t mantissa = sample >> 4;
        
        for (int j = 0; j < 7; j++) {
            if ((mantissa >> (j + 1)) == 0) {
                exponent = j;
                break;
            }
        }
        
        /* Construct A-law byte */
        alaw = sign | (exponent << 4) | ((mantissa >> (exponent + 3)) & 0x0F);
        alaw ^= 0x55;  /* Invert bits */
        output[i] = alaw;
    }
}

/**
 * Decode G.711 A-law to PCM16
 */
void g711_alaw_decode(const uint8_t *alaw, int16_t *output, uint32_t len) {
    for (uint32_t i = 0; i < len; i++) {
        output[i] = g711_alaw_decode_table[alaw[i]];
    }
}
